-- FINESSSIM Dental Studio
-- PostgreSQL baseline schema translated from the supplied D1/SQLite schema.
-- This is a preparation artifact only: it does not connect to or modify the live D1 database.
-- Keep text date/time columns initially to preserve the current API's ISO/string behavior.
-- Apply only to a NEW PostgreSQL database after choosing a provider and testing the API adapter.

CREATE TABLE IF NOT EXISTS site_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  price TEXT DEFAULT '',
  image_url TEXT DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text),
  duration_minutes INTEGER NOT NULL DEFAULT 60
);

CREATE TABLE IF NOT EXISTS staff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  position TEXT DEFAULT '',
  description TEXT DEFAULT '',
  photo_url TEXT DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS staff_schedules (
  staff_id BIGINT PRIMARY KEY,
  working_days TEXT NOT NULL,
  working_start TEXT NOT NULL,
  working_end TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  service TEXT DEFAULT '',
  message TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new',
  created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text),
  appointment_at TEXT,
  staff_id BIGINT,
  service_id BIGINT,
  notes TEXT NOT NULL DEFAULT '',
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS finance_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('income', 'expense', 'income_reversal')),
  amount BIGINT NOT NULL CHECK (amount > 0),
  category TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  booking_id BIGINT,
  service_title TEXT NOT NULL DEFAULT '',
  client_name TEXT NOT NULL DEFAULT '',
  transaction_date TEXT NOT NULL DEFAULT (CURRENT_DATE::text),
  created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text),
  event_key TEXT
);

CREATE TABLE IF NOT EXISTS admin_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id BIGINT,
  details TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
  restored_at TEXT,
  restored_transaction_id BIGINT
);

-- Operational rate-limit tables. These are intentionally not part of business-data exports.
CREATE TABLE IF NOT EXISTS public_booking_rate_limits (
  ip_hash TEXT PRIMARY KEY,
  window_started_at BIGINT NOT NULL,
  hits INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS admin_login_rate_limits (
  ip_hash TEXT PRIMARY KEY,
  window_started_at BIGINT NOT NULL,
  hits INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_bookings_date
  ON bookings (appointment_at);

CREATE INDEX IF NOT EXISTS idx_bookings_staff_date
  ON bookings (staff_id, appointment_at);

CREATE INDEX IF NOT EXISTS idx_bookings_status
  ON bookings (status);

CREATE INDEX IF NOT EXISTS idx_finance_booking
  ON finance_transactions (booking_id);

CREATE INDEX IF NOT EXISTS idx_finance_date
  ON finance_transactions (transaction_date);

CREATE UNIQUE INDEX IF NOT EXISTS idx_finance_event_key
  ON finance_transactions (event_key)
  WHERE event_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_finance_type
  ON finance_transactions (type);

-- Deliberately no foreign keys yet: the live SQLite schema has none.
-- Before adding relational constraints, validate existing rows for orphaned IDs.
-- Cloudflare's internal _cf_KV table is not application data and is not migrated.
